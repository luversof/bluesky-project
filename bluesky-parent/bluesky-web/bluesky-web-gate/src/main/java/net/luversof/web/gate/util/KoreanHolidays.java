  /** 공휴일이면 이름을(겹치면 "·"로 병기), 아니면 null 을 반환한다. */
  public static String holidayName(LocalDate date) {
    List<String> names = date != null ? HOLIDAYS.get(date) : null;
    return names != null ? String.join("·", names) : null;
  }
